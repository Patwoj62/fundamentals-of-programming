wynik1 = 3 * 2 + 1           # najpierw mnożenie, potem dodawanie
print(wynik1)                # wyświetlenie wyniku 7

wynik2 = 5 + 10 * 5          # najpierw mnożenie 10*5
print(wynik2)                # wyświetlenie wyniku 55

wynik3 = 4 + 4 / 2 ** 2      # potęga, dzielenie, dodawanie
print(wynik3)                # wyświetlenie wyniku 5.0

wynik4 = 4 % 3 % 2 % 1       # kolejne operacje modulo
print(wynik4)                # wyświetlenie wyniku 0

wynik5 = 1 + 2 % 3 ** 4 * 5  # zachowanie kolejności działań
print(wynik5)                # wyświetlenie wyniku 11

wynik6 = True != False       # porównanie wartości logicznych
print(wynik6)                # wyświetlenie True
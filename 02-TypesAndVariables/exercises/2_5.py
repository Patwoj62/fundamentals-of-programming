x = 15                       # pierwsza liczba
y = 10                       # druga liczba

print(x > y)                 # sprawdzenie czy x jest większe od y

print(x < y)                 # sprawdzenie czy x jest mniejsze od y

print(x >= y)                # sprawdzenie czy x jest większe lub równe y

print(x <= y)                # sprawdzenie czy x jest mniejsze lub równe y

print(x == y)                # sprawdzenie równości

print(x != y)                # sprawdzenie nierówności
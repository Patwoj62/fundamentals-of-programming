x = 7                                   # przypisanie wartości do x
y = 34                                  # przypisanie wartości do y

print("Before swap:", x, y)             # wyświetlenie wartości przed zamianą

temp = x                                # zapisanie starego x
x = y                                   # przypisanie y do x
y = temp                                # przypisanie starego x do y

print("After swap:", x, y)              # wyświetlenie wartości po zamianie
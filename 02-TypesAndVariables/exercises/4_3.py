a = 3                                       # pierwsza liczba
b = 5                                       # druga liczba

print(f"{a}+{b}={a+b}")                     # wyświetlenie dodawania
print(f"{a}-{b}={a-b}")                     # wyświetlenie odejmowania
print(f"{a}*{b}={a*b}")                     # wyświetlenie mnożenia
print(f"{a}/{b}={a/b}")                     # wyświetlenie dzielenia
amount = float(input("Enter amount: "))     # pobranie kwoty
vat = amount * 0.23                         # obliczenie podatku VAT

print(f"Amount  : {amount:.2f}")            # wyświetlenie kwoty z 2 miejscami po przecinku
print(f"VAT 23% : {vat:.2f}")               # wyświetlenie VAT z 2 miejscami po przecinku
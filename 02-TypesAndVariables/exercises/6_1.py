name = "Patryk"                              # wpisanie imienia
surname = "Wojtowicz"                        # wpisanie nazwiska
characters_in_name = len(name)               # liczba znaków w imieniu
characters_in_surname = len(surname)         # liczba znaków w nazwisku
full_name = name + " " + surname             # połączenie imienia i nazwiska
characters_in_full_name = len(full_name)     # liczba znaków pełnego imienia i nazwiska

print(f"Your name has {characters_in_name} characters")  # wyświetlenie długości imienia
print(f"Your surname has {characters_in_surname} characters")  # wyświetlenie długości nazwiska
print(f"Your full name has {characters_in_full_name} characters")  # wyświetlenie długości pełnego imienia i nazwiska
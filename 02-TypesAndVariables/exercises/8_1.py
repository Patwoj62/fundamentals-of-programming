r = float(input("Enter radius: "))         # pobranie promienia
PI = 3.14                                  # wartość liczby PI
area = PI * r * r                          # obliczenie pola koła
circumference = 2 * PI * r                 # obliczenie obwodu koła

print(f"Circumference = {circumference}")  # wyświetlenie obwodu

print(f"Area = {area:.2f}")                    # wyświetlenie pola
celsius = float(input("Enter temperature in Celsius: "))  # pobranie temperatury=
kelvin = celsius + 273.15                 # konwersja na Kelviny
fahrenheit = (celsius * 9 / 5) + 32       # konwersja na Fahrenheity

print(f"Temperature in Kelvin: {kelvin}")       # wyświetlenie Kelvinów
print(f"Temperature in Fahrenheit: {fahrenheit}")  # wyświetlenie Fahrenheitów
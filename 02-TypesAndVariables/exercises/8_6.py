number = int(input("Enter number: "))      # pobranie liczby dziesiętnej
binary_number = bin(number)                # konwersja na zapis binarny
hexadecimal_number = hex(number)           # konwersja na zapis szesnastkowy

print(f"Binary number: {binary_number}")   # wyświetlenie liczby binarnej
print(f"Hexadecimal number: {hexadecimal_number}")  # wyświetlenie liczby szesnastkowej